import { walkSync } from "@std/fs/walk";
import { relative, SEPARATOR } from "@std/path";

function generateIndexFile() {
  const lines = Array.from(
    walkSync("./src", { includeDirs: false, exts: [".ts"] }),
    (entry) =>
      `export * from "./${relative(".", entry.path).split(SEPARATOR).join("/")}";`,
  );

  const count = lines.length;

  lines.sort();
  lines.unshift("// This file was auto-generated by build_index.ts\n");

  Deno.writeTextFileSync("./index.ts", lines.join("\n"));

  console.log(`✅ Successfully generated "./index.ts" with ${count} exports.`);
}

if (import.meta.main) {
  generateIndexFile();
}
